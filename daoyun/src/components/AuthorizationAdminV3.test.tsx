it("restores appointment trigger focus after the loading screen replaces the original button", async () => {
  let finishRefresh!: (page: { assignments: typeof assignment[]; nextCursor: null }) => void
  const refresh = new Promise<{ assignments: typeof assignment[]; nextCursor: null }>(resolve => { finishRefresh = resolve })
  vi.mocked(listAuthorizationAssignments).mockResolvedValueOnce({ assignments: [], nextCursor: null }).mockReturnValueOnce(refresh)
  const user = userEvent.setup(); render(<AuthorizationAdminPanel {...props} query="view=assignments" />)
  const originalTrigger = await screen.findByRole("button", { name: "新增授权" })
  originalTrigger.focus(); await user.keyboard("{Enter}")
  const dialog = screen.getByRole("dialog", { name: "分配角色" })
  await user.type(within(dialog).getByLabelText("搜索用户"), "tester")
  await user.click(await within(dialog).findByRole("button", { name: "选择指定会员 @tester" }))
  await user.selectOptions(within(dialog).getByLabelText("自定义角色"), role.id)
  await user.selectOptions(within(dialog).getByLabelText("作用板块"), board.id)
  await user.click(within(dialog).getByRole("button", { name: "预览任命" }))
  await user.click(within(screen.getByRole("alertdialog", { name: "确认任命管理人员" })).getByRole("button", { name: "确认任命" }))
  await screen.findByText("正在读取角色与权限")
  expect(originalTrigger.isConnected).toBe(false)
  finishRefresh({ assignments: [assignment], nextCursor: null })
  const currentTrigger = await screen.findByRole("button", { name: "新增授权" })
  await waitFor(() => expect(currentTrigger).toHaveFocus())
  expect(createAuthorizationAssignment).toHaveBeenCalledTimes(1)
})


