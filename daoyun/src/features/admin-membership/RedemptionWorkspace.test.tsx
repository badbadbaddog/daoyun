import {cleanup,fireEvent,render,screen,waitFor} from "@testing-library/react"
import userEvent from "@testing-library/user-event"
import {afterEach,beforeEach,expect,it,vi} from "vitest"
import {RedemptionWorkspace} from "./RedemptionWorkspace"
import {listRedemptionProducts,putRedemptionProduct,RedemptionApiError,type RedemptionProduct} from "../../api/redemptions"
import {listStandardEntitlementTypes} from "../../api/admin"
vi.mock("../../api/redemptions",async()=>({...await vi.importActual("../../api/redemptions"),listRedemptionProducts:vi.fn(),putRedemptionProduct:vi.fn()}))
vi.mock("../../api/admin",()=>({listStandardEntitlementTypes:vi.fn()}))
const kind="019fc900-0000-7000-8000-000000000802",id="019fc900-0000-7000-8000-000000000803"
const product:RedemptionProduct={id,name:"月度兑换",entitlement_type_id:kind,type_version:1,price:100,duration_days:7,per_user_limit:1,enabled:true,revision:1,permission_keys:["topic.poll.create"],quotas:{"attachment.file.bytes":1024},unavailable_reason:null}
beforeEach(()=>{vi.resetAllMocks();vi.mocked(listStandardEntitlementTypes).mockResolvedValue([])})
afterEach(()=>{cleanup();vi.restoreAllMocks()})
it("keeps product writes unavailable when the provider is disabled",async()=>{
 vi.mocked(listRedemptionProducts).mockResolvedValue({enabled:false,products:[],next_cursor:null})
 render(<RedemptionWorkspace csrfToken="csrf" canWrite canReadTypes/>)
 expect(await screen.findByText("请先在插件管理安装并启用积分兑换。")).toBeInTheDocument()
 expect(screen.getByRole("button",{name:"新增商品"})).toBeDisabled()
})
it("does not expose product mutation controls to a read-only administrator",async()=>{
 vi.mocked(listRedemptionProducts).mockResolvedValue({enabled:true,products:[],next_cursor:null})
 render(<RedemptionWorkspace csrfToken="csrf" canWrite={false} canReadTypes={false}/>)
 await screen.findByText("暂无兑换商品")
 expect(screen.queryByRole("button",{name:"新增商品"})).not.toBeInTheDocument()
 await userEvent.click(screen.getByRole("button",{name:"刷新商品"}))
})
it("explains the missing entitlement prerequisite",async()=>{
 vi.mocked(listRedemptionProducts).mockResolvedValue({enabled:true,products:[],next_cursor:null})
 render(<RedemptionWorkspace csrfToken="csrf" canWrite canReadTypes/>)
 expect(await screen.findByText("暂无可用权益类型，请先在会员权益中创建并发布权益。")).toBeInTheDocument()
 expect(screen.getByRole("button",{name:"新增商品"})).toBeDisabled()
})
it("preserves every draft field on conflict, finds a paginated target and updates only its revision",async()=>{
 vi.mocked(listRedemptionProducts).mockResolvedValueOnce({enabled:true,products:[product],next_cursor:null})
  .mockResolvedValueOnce({enabled:true,products:[],next_cursor:kind})
  .mockResolvedValueOnce({enabled:true,products:[{...product,revision:2,price:900}],next_cursor:null})
 vi.mocked(putRedemptionProduct).mockRejectedValueOnce(new RedemptionApiError(409,"redemption.conflict","版本冲突"))
  .mockResolvedValueOnce({...product,revision:3,name:"保留草稿",price:123,duration_days:30,per_user_limit:4,enabled:false})
 render(<RedemptionWorkspace csrfToken="csrf" canWrite canReadTypes/>)
 await userEvent.click(await screen.findByRole("button",{name:"编辑 月度兑换"}))
 fireEvent.change(screen.getByLabelText("商品名称"),{target:{value:"保留草稿"}})
 fireEvent.change(screen.getByLabelText("所需积分"),{target:{value:"123"}})
 fireEvent.change(screen.getByLabelText("有效天数"),{target:{value:"30"}})
 fireEvent.change(screen.getByLabelText("每人兑换上限"),{target:{value:"4"}})
 await userEvent.click(screen.getByLabelText("上架，允许成员兑换"))
 await userEvent.click(screen.getByRole("button",{name:"保存商品"}))
 await screen.findByRole("alert")
 expect(screen.getByRole("button",{name:"保存商品"})).toBeDisabled()
 await userEvent.click(screen.getByRole("button",{name:"重新加载商品"}))
 await waitFor(()=>expect(screen.getByRole("button",{name:"保存商品"})).toBeEnabled())
 expect(screen.getByLabelText("商品名称")).toHaveValue("保留草稿")
 expect(screen.getByLabelText("所需积分")).toHaveValue(123)
 expect(screen.getByLabelText("有效天数")).toHaveValue(30)
 expect(screen.getByLabelText("每人兑换上限")).toHaveValue(4)
 expect(screen.getByLabelText("上架，允许成员兑换")).not.toBeChecked()
 await userEvent.click(screen.getByRole("button",{name:"保存商品"}))
 await waitFor(()=>expect(putRedemptionProduct).toHaveBeenCalledTimes(2))
 expect(vi.mocked(putRedemptionProduct).mock.calls[1]).toEqual([id,{name:"保留草稿",entitlement_type_id:kind,type_version:1,price:123,duration_days:30,per_user_limit:4,enabled:false,expected_revision:2},"csrf"])
})
it("keeps the conflict lock and draft when refresh fails",async()=>{
 vi.mocked(listRedemptionProducts).mockResolvedValueOnce({enabled:true,products:[product],next_cursor:null}).mockRejectedValueOnce(new Error("读取失败"))
 vi.mocked(putRedemptionProduct).mockRejectedValueOnce(new RedemptionApiError(409,"redemption.conflict","版本冲突"))
 render(<RedemptionWorkspace csrfToken="csrf" canWrite canReadTypes/>)
 await userEvent.click(await screen.findByRole("button",{name:"编辑 月度兑换"}))
 fireEvent.change(screen.getByLabelText("商品名称"),{target:{value:"保留草稿"}})
 await userEvent.click(screen.getByRole("button",{name:"保存商品"}));await screen.findByRole("alert")
 await userEvent.click(screen.getByRole("button",{name:"重新加载商品"}))
 await screen.findByText("读取失败")
 expect(screen.getByLabelText("商品名称")).toHaveValue("保留草稿")
 expect(screen.getByRole("button",{name:"保存商品"})).toBeDisabled()
})
it("freezes an unknown creation, retries the original UUID and input, and keeps a later conflict unknown",async()=>{
 vi.mocked(listStandardEntitlementTypes).mockResolvedValue([{id:kind,internalKey:"vip",displayName:"会员",status:"active",currentVersion:1,permissionKeys:[],quotas:{},revision:1,createdAt:"2026-01-01Z",updatedAt:"2026-01-01Z"}])
 vi.mocked(listRedemptionProducts).mockResolvedValue({enabled:true,products:[],next_cursor:null})
 vi.mocked(putRedemptionProduct).mockRejectedValueOnce(new TypeError("响应丢失"))
  .mockRejectedValueOnce(new RedemptionApiError(409,"redemption.conflict","商品已存在"))
 render(<RedemptionWorkspace csrfToken="csrf" canWrite canReadTypes/>)
 await userEvent.click(await screen.findByRole("button",{name:"新增商品"}))
 await userEvent.type(screen.getByLabelText("商品名称"),"新会员商品")
 await userEvent.selectOptions(screen.getByLabelText("兑换权益"),kind)
 await userEvent.click(screen.getByRole("button",{name:"保存商品"}));await screen.findByRole("alert")
 expect(screen.getByLabelText("商品名称")).toBeDisabled()
 expect(screen.getByRole("button",{name:"取消"})).toBeDisabled()
 await userEvent.keyboard("{Escape}");expect(screen.getByRole("dialog")).toBeInTheDocument()
 await userEvent.click(screen.getByRole("button",{name:"使用原商品请求重试"}))
 await waitFor(()=>expect(putRedemptionProduct).toHaveBeenCalledTimes(2))
 expect(vi.mocked(putRedemptionProduct).mock.calls[1]).toEqual(vi.mocked(putRedemptionProduct).mock.calls[0])
 await userEvent.click(screen.getByRole("button",{name:"核实当前商品"}))
 await screen.findByText(/尚未找到.*不能确认.*失败/)
 expect(screen.getByLabelText("商品名称")).toBeDisabled()
})
it("recovers an unknown create only after explicit adoption of an existing revision, retaining its UUID",async()=>{
 vi.mocked(listStandardEntitlementTypes).mockResolvedValue([{id:kind,internalKey:"vip",displayName:"会员",status:"active",currentVersion:1,permissionKeys:[],quotas:{},revision:1,createdAt:"2026-01-01Z",updatedAt:"2026-01-01Z"}])
 vi.mocked(listRedemptionProducts).mockResolvedValueOnce({enabled:true,products:[],next_cursor:null})
 vi.mocked(putRedemptionProduct).mockRejectedValueOnce(new TypeError("响应丢失"))
 render(<RedemptionWorkspace csrfToken="csrf" canWrite canReadTypes/>)
 await userEvent.click(await screen.findByRole("button",{name:"新增商品"}))
 await userEvent.type(screen.getByLabelText("商品名称"),"原草稿")
 await userEvent.selectOptions(screen.getByLabelText("兑换权益"),kind)
 await userEvent.click(screen.getByRole("button",{name:"保存商品"}));await screen.findByRole("alert")
 const created=vi.mocked(putRedemptionProduct).mock.calls[0][0]
 vi.mocked(listRedemptionProducts).mockResolvedValueOnce({enabled:true,products:[{...product,id:created,revision:1}],next_cursor:null})
 await userEvent.click(screen.getByRole("button",{name:"核实当前商品"}))
 await screen.findByRole("button",{name:"采用已读取的商品版本"})
 expect(screen.getByLabelText("商品名称")).toBeDisabled()
 await userEvent.click(screen.getByRole("button",{name:"采用已读取的商品版本"}))
 expect(screen.getByLabelText("商品名称")).toHaveValue("原草稿")
 expect(screen.getByLabelText("商品名称")).toBeEnabled()
 vi.mocked(putRedemptionProduct).mockResolvedValueOnce({...product,id:created,revision:2})
 await userEvent.click(screen.getByRole("button",{name:"保存商品"}))
 await waitFor(()=>expect(putRedemptionProduct).toHaveBeenCalledTimes(2))
 expect(vi.mocked(putRedemptionProduct).mock.calls[1][0]).toBe(created)
 expect(vi.mocked(putRedemptionProduct).mock.calls[1][1].expected_revision).toBe(1)
})
it("shows the immutable product snapshot and disables an open draft after permission withdrawal",async()=>{
 vi.mocked(listRedemptionProducts).mockResolvedValue({enabled:true,products:[product],next_cursor:null})
 const view=render(<RedemptionWorkspace csrfToken="csrf" canWrite canReadTypes/>)
 await screen.findByText("月度兑换")
 expect(screen.getByText("发起投票")).toBeInTheDocument()
 expect(screen.getByText(/单文件字节数/)).toBeInTheDocument()
 await userEvent.click(screen.getByRole("button",{name:"编辑 月度兑换"}))
 view.rerender(<RedemptionWorkspace csrfToken="csrf" canWrite={false} canReadTypes/>)
 expect(screen.getByLabelText("商品名称")).toBeDisabled()
 expect(screen.getByRole("button",{name:"保存商品"})).toBeDisabled()
})
