import { mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, isAbsolute, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import openapiTS, { astToString } from "openapi-typescript"

export const DEFAULT_INPUT = "http://127.0.0.1:3000/api/v1/openapi.json"
export const DEFAULT_OUTPUT = "src/api/generated.d.ts"

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")

export function parseArguments(args) {
  let input = DEFAULT_INPUT
  let output = DEFAULT_OUTPUT
  let check = false

  for (let index = 0; index < args.length; index += 1) {
    const flag = args[index]
    if (flag === "--input" || flag === "-i") {
      input = requireValue(args, index, flag)
      index += 1
      continue
    }
    if (flag === "--output" || flag === "-o") {
      output = requireValue(args, index, flag)
      index += 1
      continue
    }
    if (flag === "--check") {
      check = true
      continue
    }
    throw new Error(`未知参数: ${flag}`)
  }

  if (!input.trim()) {
    throw new Error("OpenAPI 输入不能为空")
  }
  if (!output.toLocaleLowerCase().endsWith(".d.ts")) {
    throw new Error("生成文件必须使用 .d.ts 扩展名")
  }

  return { input, output, check }
}

export async function generateApiClient({
  input = DEFAULT_INPUT,
  output = DEFAULT_OUTPUT,
  check = false,
} = {}) {
  const { source, cwd } = await loadInput(input)
  const outputPath = isAbsolute(output) ? output : resolve(projectRoot, output)

  // Source: https://openapi-ts.dev/introduction
  const ast = await openapiTS(source, cwd ? { cwd } : undefined)
  const generated = renderDeclaration(ast)

  if (check) {
    const existing = await readFile(outputPath, "utf8").catch(() => {
      throw new Error(`生成文件不存在: ${outputPath}`)
    })
    if (existing !== generated) {
      throw new Error(`生成文件与 OpenAPI 文档不一致: ${outputPath}`)
    }
    return outputPath
  }

  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, generated, "utf8")
  return outputPath
}

function renderDeclaration(ast) {
  return [
    "// @generated by scripts/generate-api-client.mjs; do not edit manually.",
    "// Source schema: /api/v1/openapi.json",
    astToString(ast).trim(),
    "",
  ].join("\n")
}

function requireValue(args, index, flag) {
  const value = args[index + 1]
  if (!value || value.startsWith("-")) {
    throw new Error(`${flag} 需要一个值`)
  }
  return value
}

async function loadInput(input) {
  try {
    const url = new URL(input)
    if (url.protocol === "http:" || url.protocol === "https:") return { source: input }
  } catch {
    // Treat non-URL values as local schema paths.
  }
  const localPath = isAbsolute(input) ? input : resolve(projectRoot, input)
  return {
    source: await readFile(localPath, "utf8"),
    cwd: dirname(localPath),
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  try {
    const options = parseArguments(process.argv.slice(2))
    const outputPath = await generateApiClient(options)
    process.stdout.write(options.check
      ? `OpenAPI 类型校验通过：${outputPath}\n`
      : `OpenAPI 类型已生成：${outputPath}\n`)
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error)
    process.stderr.write(`OpenAPI 类型生成失败：${message}\n`)
    process.exitCode = 1
  }
}
